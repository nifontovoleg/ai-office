import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const output=fileURLToPath(new URL('../../output/playwright/',import.meta.url));
await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:process.env.OFFICE_BROWSER||'msedge',headless:true});
const base=process.env.OFFICE_URL||'http://127.0.0.1:4197';
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page=await context.newPage();
const report={started:new Date().toISOString(),checks:[],consoleErrors:[],networkErrors:[],accessibility:[],screenshots:[]};
const expectedErrors=new Set();
page.on('pageerror',e=>report.consoleErrors.push(e.message));
page.on('console',m=>{if(m.type()==='error'&&!/Failed to load resource/.test(m.text()))report.consoleErrors.push(m.text());});
page.on('response',r=>{if(r.status()>=400&&!expectedErrors.has(new URL(r.url()).pathname))report.networkErrors.push(`${r.status()} ${r.url()}`);});
page.on('requestfailed',r=>{if(!/ERR_ABORTED/.test(r.failure()?.errorText||''))report.networkErrors.push(r.failure()?.errorText+' '+r.url());});
const check=(name)=>{report.checks.push(name);console.log('PASS '+name);};
const screenshot=async name=>{await page.screenshot({path:output+name,fullPage:true});report.screenshots.push(name);};
const nav=async name=>{await page.getByRole('navigation',{name:'Основное меню'}).getByRole('button',{name,exact:true}).click();};
const overflow=async()=>{
  const geometry=await page.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(geometry.scroll<=geometry.client,JSON.stringify(geometry));
};
const a11y=async name=>{
  const result=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze();
  const issues=result.violations.map(v=>({id:v.id,impact:v.impact,description:v.description,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}));
  report.accessibility.push({screen:name,violations:issues});
  assert.equal(issues.length,0,'Accessibility '+name+': '+JSON.stringify(issues));
  check('WCAG AA automation: '+name);
};

  check('282 catalog searchable with category; original instruction opens directly');
  await a11y('original profile dialog');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  assert.equal(await page.getByRole('button',{name:'Инструкция',exact:true}).evaluate(el=>el===document.activeElement),true);
  check('Dialog Escape closes and restores focus');

  await nav('Настройки');

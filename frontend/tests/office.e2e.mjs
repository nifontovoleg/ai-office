  await page.keyboard.press('Escape');

  await page.getByRole('button',{name:'Новая задача',exact:true}).first().click();
  const form=page.getByRole('dialog',{name:'Новая задача'});
  await form.getByLabel('Название задачи').fill('Проверить понятность брифа');
  await form.getByLabel('Ожидаемый результат').fill('Краткое заключение и список уточнений.');
  await form.getByLabel('Приоритет').selectOption('high');
  await form.getByLabel('Координатор ИИ-агентов',{exact:true}).check();
  await form.getByLabel('Исследователь пользовательского опыта',{exact:true}).check();
  await form.getByLabel('Название этапа 1').fill('Сформулировать критерии');
  await form.getByLabel('Название этапа 2').fill('Проверить бриф');

  assert.match(await page.locator('.task-cards').innerText(),/Проверить понятность брифа/);
  await page.reload();
  await page.getByRole('heading',{name:'Офис агентов.'}).waitFor();
  const persisted=await (await context.request.get(`${base}/api/state/${qaProject}`)).json();
